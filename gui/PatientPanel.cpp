#include "PatientPanel.h"

#include "../model/EmergencyPatient.h"
#include "../model/FollowUpPatient.h"
#include "../model/GeneralPatient.h"
#include "../utils/ClinicException.h"
#include "../utils/IDGenerator.h"

#include <QComboBox>
#include <QFormLayout>
#include <QHeaderView>
#include <QHBoxLayout>
#include <QLineEdit>
#include <QMessageBox>
#include <QPushButton>
#include <QTableWidget>
#include <QVBoxLayout>

#include <exception>

PatientPanel::PatientPanel(Controller::ClinicManager& manager, QWidget* parent)
    : QWidget(parent), clinicManager(manager), idInput(new QLineEdit(this)),
      nameInput(new QLineEdit(this)), ageInput(new QLineEdit(this)),
      contactInput(new QLineEdit(this)), typeCombo(new QComboBox(this)),
      patientTable(new QTableWidget(this)), addButton(new QPushButton(tr("Register Patient"), this)),
      updateButton(new QPushButton(tr("Update Selected"), this)) {
    auto* root = new QVBoxLayout(this);
    auto* form = new QFormLayout();

    idInput->setReadOnly(true);
    idInput->setToolTip(tr("Patient IDs are generated by the system."));
    ageInput->setPlaceholderText(tr("0–120"));
    contactInput->setPlaceholderText(tr("Phone"));
    typeCombo->addItems({tr("General"), tr("Emergency"), tr("Follow-Up")});
    typeCombo->setToolTip(tr("Choose a patient category; emergency patients are highlighted in the table."));

    form->addRow(tr("Patient ID:"), idInput);
    form->addRow(tr("Full name:"), nameInput);
    form->addRow(tr("Age:"), ageInput);
    form->addRow(tr("Contact:"), contactInput);
    form->addRow(tr("Category:"), typeCombo);

    auto* buttons = new QHBoxLayout();
    auto* deleteButton = new QPushButton(tr("Delete Selected"), this);
    auto* clearButton = new QPushButton(tr("Clear Form"), this);
    addButton->setToolTip(tr("Register a new patient record."));
    updateButton->setToolTip(tr("Update the selected patient's name, age, and contact details."));
    deleteButton->setToolTip(tr("Permanently remove the selected patient record."));
    buttons->addWidget(addButton);
    buttons->addWidget(updateButton);
    buttons->addWidget(deleteButton);
    buttons->addWidget(clearButton);

    patientTable->setColumnCount(5);
    patientTable->setHorizontalHeaderLabels({tr("Patient ID"), tr("Name"), tr("Age"), tr("Contact"), tr("Category")});
    patientTable->horizontalHeader()->setSectionResizeMode(QHeaderView::Stretch);
    patientTable->setSelectionBehavior(QAbstractItemView::SelectRows);
    patientTable->setSelectionMode(QAbstractItemView::SingleSelection);
    patientTable->setEditTriggers(QAbstractItemView::NoEditTriggers);

    root->addLayout(form);
    root->addLayout(buttons);
    root->addWidget(patientTable, 1);

    connect(addButton, &QPushButton::clicked, this, &PatientPanel::addPatient);
    connect(updateButton, &QPushButton::clicked, this, &PatientPanel::updateSelectedPatient);
    connect(deleteButton, &QPushButton::clicked, this, &PatientPanel::deleteSelectedPatient);
    connect(clearButton, &QPushButton::clicked, this, [this]() { clearForm(true); });
    connect(patientTable, &QTableWidget::cellClicked, this, [this](int, int) { loadSelectedPatient(); });

    clearForm(true);
    refreshTable();
}

void PatientPanel::addPatient() {
    bool ageOk = false;
    const int age = ageInput->text().trimmed().toInt(&ageOk);
    const QString name = nameInput->text().trimmed();
    const QString contact = contactInput->text().trimmed();
    const std::string id = idInput->text().toStdString();

    if (!ageOk || age < 0 || age > 120) {
        showError(tr("Age must be a whole number between 0 and 120."));
        return;
    }
    if (name.isEmpty() || contact.isEmpty()) {
        showError(tr("Please enter the patient's name and contact information."));
        return;
    }
    if (clinicManager.getDatabase().findPatientByID(id) != nullptr) {
        showError(tr("A patient with this ID already exists. Generate a new ID and try again."));
        clearForm(true);
        return;
    }

    Model::PatientRecord* patient = nullptr;
    const QString type = typeCombo->currentText();
    try {
        if (type == tr("Emergency")) {
            patient = new Model::EmergencyPatient(id, name.toStdString(), age, contact.toStdString());
        } else if (type == tr("Follow-Up")) {
            patient = new Model::FollowUpPatient(id, name.toStdString(), age, contact.toStdString());
        } else {
            patient = new Model::GeneralPatient(id, name.toStdString(), age, contact.toStdString());
        }
        clinicManager.registerPatient(patient);
        patient = nullptr; // ClinicDatabase owns successfully registered records.
        refreshTable();
        clearForm(true);
    } catch (const Utils::ClinicException& error) {
        delete patient;
        showError(QString::fromUtf8(error.what()));
    } catch (const std::exception& error) {
        delete patient;
        showError(tr("Could not register patient: %1").arg(QString::fromUtf8(error.what())));
    }
}

void PatientPanel::updateSelectedPatient() {
    Model::PatientRecord* patient = selectedPatient();
    if (!patient) {
        showError(tr("Select a patient from the table before updating."));
        return;
    }
    bool ageOk = false;
    const int age = ageInput->text().trimmed().toInt(&ageOk);
    const QString name = nameInput->text().trimmed();
    const QString contact = contactInput->text().trimmed();
    if (!ageOk || age < 0 || age > 120 || name.isEmpty() || contact.isEmpty()) {
        showError(tr("Enter a non-empty name and contact, and an age between 0 and 120."));
        return;
    }

    try {
        patient->setName(name.toStdString());
        patient->setAge(age);
        patient->setContactInfo(contact.toStdString());
        refreshTable();
    } catch (const Utils::ClinicException& error) {
        showError(QString::fromUtf8(error.what()));
    } catch (const std::exception& error) {
        showError(tr("Could not update patient: %1").arg(QString::fromUtf8(error.what())));
    }
}

void PatientPanel::deleteSelectedPatient() {
    Model::PatientRecord* patient = selectedPatient();
    if (!patient) {
        showError(tr("Select a patient from the table before deleting."));
        return;
    }
    const std::string id = patient->getPatientID();
    if (QMessageBox::question(this, tr("Delete patient"), tr("Delete patient %1?").arg(QString::fromStdString(id))) != QMessageBox::Yes) {
        return;
    }
    clinicManager.deletePatient(id);
    refreshTable();
    clearForm(true);
}

void PatientPanel::loadSelectedPatient() {
    Model::PatientRecord* patient = selectedPatient();
    if (!patient) return;
    idInput->setText(QString::fromStdString(patient->getPatientID()));
    nameInput->setText(QString::fromStdString(patient->getName()));
    ageInput->setText(QString::number(patient->getAge()));
    contactInput->setText(QString::fromStdString(patient->getContactInfo()));
    typeCombo->setCurrentText(QString::fromStdString(patient->getPatientType()));
    addButton->setEnabled(false);
    updateButton->setEnabled(true);
}

void PatientPanel::refreshTable() {
    patientTable->setRowCount(0);
    const auto& patients = clinicManager.getDatabase().getPatients();
    for (const Model::PatientRecord* patient : patients) {
        if (!patient) continue;
        const int row = patientTable->rowCount();
        patientTable->insertRow(row);
        const QString values[] = {
            QString::fromStdString(patient->getPatientID()),
            QString::fromStdString(patient->getName()),
            QString::number(patient->getAge()),
            QString::fromStdString(patient->getContactInfo()),
            QString::fromStdString(patient->getPatientType())
        };
        for (int column = 0; column < 5; ++column) {
            auto* item = new QTableWidgetItem(values[column]);
            if (patient->getPatientType() == "Emergency") {
                item->setBackground(QColor(255, 220, 220));
            } else if (patient->getPatientType() == "Follow-Up") {
                item->setBackground(QColor(225, 238, 255));
            }
            patientTable->setItem(row, column, item);
        }
    }
}

Model::PatientRecord* PatientPanel::selectedPatient() const {
    const int row = patientTable->currentRow();
    if (row < 0) return nullptr;
    QTableWidgetItem* idItem = patientTable->item(row, 0);
    return idItem ? clinicManager.getDatabase().findPatientByID(idItem->text().toStdString()) : nullptr;
}

void PatientPanel::clearForm(bool generateNextID) {
    nameInput->clear();
    ageInput->clear();
    contactInput->clear();
    typeCombo->setCurrentIndex(0);
    patientTable->clearSelection();
    addButton->setEnabled(true);
    updateButton->setEnabled(false);
    idInput->setText(QString::fromStdString(generateNextID ? Utils::IDGenerator::generatePatientID() : std::string()));
}

void PatientPanel::showError(const QString& message) {
    QMessageBox::warning(this, tr("Patient record"), message);
}
